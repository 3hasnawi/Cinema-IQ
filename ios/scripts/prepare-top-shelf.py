#!/usr/bin/env python3
"""Generate optional signing metadata without requiring an App Group for ordinary sideloads."""
import json
import os
from pathlib import Path
import plistlib
import re

root = Path(__file__).resolve().parents[1]
generated = root / 'Generated'
generated.mkdir(exist_ok=True)
group = os.environ.get('CINEMAIQ_APP_GROUP', '').strip()
if group and not re.fullmatch(r'group\.[A-Za-z0-9][A-Za-z0-9.\-]{2,150}', group):
    raise SystemExit('CINEMAIQ_APP_GROUP must be a registered group.<identifier>, or empty')
(generated / 'TopShelfConfiguration.swift').write_text(
    '// Generated by prepare-top-shelf.py. No account credentials.\n'
    'enum TVShelfConfiguration {\n'
    '    static let groupIdentifier: String? = ' + (json.dumps(group) if group else 'nil') + '\n}\n')
entitlements = {'com.apple.security.application-groups': [group]} if group else {}
(generated / 'TopShelf.entitlements').write_bytes(plistlib.dumps(entitlements))
# Read the host's current values so future authorized version bumps cannot leave the extension behind.
spec = (root / 'project.yml').read_text()
host = spec.split('\n  CinemaIQTV:\n', 1)[1].split('\n  CinemaIQTopShelf:\n', 1)[0].split('\n  CinemaIQUITests:\n', 1)[0]
version = re.search(r'MARKETING_VERSION:\s*"([^"\n]+)"', host).group(1)
build = re.search(r'CURRENT_PROJECT_VERSION:\s*"([^"\n]+)"', host).group(1)
info = {'CFBundleDisplayName': 'Cinema iQ Top Shelf', 'CFBundleName': '$(PRODUCT_NAME)',
        'CFBundleIdentifier': '$(PRODUCT_BUNDLE_IDENTIFIER)', 'CFBundleExecutable': '$(EXECUTABLE_NAME)',
        'CFBundlePackageType': 'XPC!', 'CFBundleShortVersionString': version, 'CFBundleVersion': build,
        'CFBundleDevelopmentRegion': 'ar',
        'NSExtension': {'NSExtensionPointIdentifier': 'com.apple.tv-services',
                        'NSExtensionPrincipalClass': '$(PRODUCT_MODULE_NAME).ContentProvider'},
        'NSAppTransportSecurity': {'NSAllowsArbitraryLoads': True}}
(generated / 'TopShelf-Info.plist').write_bytes(plistlib.dumps(info))
print('Top Shelf configuration:', 'shared group enabled' if group else 'public featured fallback; no App Group entitlement')
